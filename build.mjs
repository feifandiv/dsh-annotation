/**
 * Bundle the plain-JS sources into the single browser artifact the Harness
 * module loader expects.
 *
 * The client module format is one `window.__ModuleLoader__.load({...})` call:
 * the factory receives only the shared module table (`react`), so the bundle
 * cannot import project files at runtime. This script concatenates the ordered
 * sources, strips the ESM `export` keywords that let the same files be tested
 * under Node, embeds the locale dictionaries, and writes `client.js`.
 *
 * Run with the bundled Node: `node build.mjs`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');

const sources = ['src/core.js', 'src/engine.js', 'src/ui.js', 'src/strings.js', 'src/plugin.js'];
const stripExports = (source) => source.replace(/^export\s+(?=(?:function|const|let|class)\b)/gm, '');
const chunks = sources.map((file) => {
  const body = stripExports(read(file)).trimEnd();
  return `/* ---- ${file} ---- */\n${body}\n`;
});

const out = `window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    /* Generated by build.mjs from src/*.js. Do not edit by hand. */
    const React = require('react');
    const h = React.createElement;

${chunks.join('\n')}
    return { inject: ANNO_INJECT, apply: annoApply };
  },
});
`;

fs.writeFileSync(path.join(root, 'client.js'), out);
const bytes = Buffer.byteLength(out);
console.log('wrote client.js (' + bytes + ' bytes)');
